// Largest facet value a UI paint mask may carry. Seam and support paint are
// 0/1/2 (none/enforcer/blocker); fan paint encodes lines and speed as
// `1 + (lines - 1) * 21 + speed / 5` (libslic3r FanPaint.hpp), 147 at most.
constexpr uint8_t MAX_SEAM_SUPPORT_FACET_VALUE = 2;
constexpr uint8_t MAX_FAN_FACET_VALUE = 147;

// A decoded UI paint mask (seam, support or fan), one value per facet.
struct SeamFacetDecode {
    std::vector<uint8_t> facets;
    size_t painted = 0;
    size_t enforcers = 0;
    size_t blockers = 0;
    bool ok = true;
    std::string error;
};

struct FacetKey {
    int64_t x = 0;
    int64_t y = 0;
    int64_t z = 0;

    bool operator==(const FacetKey& other) const {
        return x == other.x && y == other.y && z == other.z;
    }
};

// A painted facet of the source STL, in the file's own coordinates.
struct RawPaintedFacet {
    std::array<float, 9> xyz{};  // three vertices
    uint8_t value = 0;
};

// Which facet order a paint mask was recognized in.
enum class MaskFacetOrder {
    Unknown,    // not a binary STL, or a length that names no known order
    File,       // the raw file order
    ExactPass,  // the order admesh's exact pass leaves
};


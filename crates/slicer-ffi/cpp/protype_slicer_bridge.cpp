// Paths cross the bridge as UTF-8. MSVC reads a narrow std::string handed to
// std::fstream or std::filesystem::path in the ANSI code page, so on Windows
// every non-ASCII path failed to open: "cannot open input mesh:
// C:\Users\Алексей\Downloads\...". Every file this bridge opens itself goes
// through utf8_path; going back to text, use path::u8string(), not string().
// libslic3r's own loaders already take UTF-8 (boost::nowide).
inline std::filesystem::path utf8_path(const std::string& path) {
    return std::filesystem::u8path(path);
}


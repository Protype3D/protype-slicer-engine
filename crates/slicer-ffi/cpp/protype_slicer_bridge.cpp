// The pitch the stub draws the whole plate at: the finest one on it.
// `plate_layer_height` is what libslic3r slices every object at that has no
// layer_height of its own; an object whose object_overrides carry one is
// sliced at that instead. The stub has always drawn the finest of them, and
// slicer-rpc's tests/handshake.rs pins that layer count; it predicts no real
// G-code, where objects of different pitches interleave by Z. A value that
// is not a positive number is skipped (object.set_override only accepts
// 0.05–0.6 mm).
float stub_layer_pitch(float plate_layer_height, const BridgeProcessSettings& settings) {
    float finest = plate_layer_height;
    for (const BridgeObjectInputs& obj : settings.objects) {
        for (const auto& ov : obj.object_overrides) {
            if (std::string(ov.key) != "layer_height") continue;
            // The classic locale, as libslic3r reads config text: a comma
            // decimal separator must not make every override unreadable.
            std::istringstream text{std::string(ov.value)};
            text.imbue(std::locale::classic());
            float own = 0.0f;
            if ((text >> own) && std::isfinite(own) && own > 0.0f) {
                finest = std::min(finest, own);
            }
        }
    }
    return std::max(finest, 0.01f);
}


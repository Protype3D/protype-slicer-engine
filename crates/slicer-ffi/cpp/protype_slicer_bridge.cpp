int base64_value(char ch) {
    if ('A' <= ch && ch <= 'Z') return ch - 'A';
    if ('a' <= ch && ch <= 'z') return ch - 'a' + 26;
    if ('0' <= ch && ch <= '9') return ch - '0' + 52;
    if (ch == '+') return 62;
    if (ch == '/') return 63;
    return -1;
}

bool decode_base64(const std::string& input, std::string& out, std::string& error) {
    out.clear();
    int value = 0;
    int bits = -8;
    for (char ch : input) {
        if (ch == '=') break;
        if (std::isspace(static_cast<unsigned char>(ch))) continue;
        const int decoded = base64_value(ch);
        if (decoded < 0) {
            error = "invalid base64 character";
            return false;
        }
        value = (value << 6) | decoded;
        bits += 6;
        if (bits >= 0) {
            out.push_back(static_cast<char>((value >> bits) & 0xff));
            bits -= 8;
        }
    }
    return true;
}

SeamFacetDecode decode_ui_facets_rle(const std::string& b64, uint8_t max_value) {
    SeamFacetDecode out;
    if (b64.empty()) return out;

    std::string raw;
    if (!decode_base64(b64, raw, out.error)) {
        out.ok = false;
        return out;
    }

    if (raw.size() % 5 != 0) {
        out.ok = false;
        out.error = "length is not a multiple of 5";
        return out;
    }

    for (std::size_t off = 0; off < raw.size(); off += 5) {
        const auto value = static_cast<uint8_t>(raw[off]);
        const uint32_t run =
            static_cast<uint8_t>(raw[off + 1]) |
            (static_cast<uint32_t>(static_cast<uint8_t>(raw[off + 2])) << 8) |
            (static_cast<uint32_t>(static_cast<uint8_t>(raw[off + 3])) << 16) |
            (static_cast<uint32_t>(static_cast<uint8_t>(raw[off + 4])) << 24);

        if (value > max_value) {
            out.ok = false;
            out.error = "facet value exceeds " + std::to_string(max_value);
            return out;
        }
        out.facets.insert(out.facets.end(), run, value);
        if (value != 0) out.painted += run;
        if (value == 1) out.enforcers += run;
        if (value == 2) out.blockers += run;
    }
    return out;
}

FacetKey facet_key(float ax, float ay, float az,
                   float bx, float by, float bz,
                   float cx, float cy, float cz) {
    constexpr double scale = 1000.0;  // 0.001 mm bins survive STL repair jitter.
    return FacetKey{
        static_cast<int64_t>(std::llround(((ax + bx + cx) / 3.0) * scale)),
        static_cast<int64_t>(std::llround(((ay + by + cy) / 3.0) * scale)),
        static_cast<int64_t>(std::llround(((az + bz + cz) / 3.0) * scale)),
    };
}

// admesh's exact-pass test for a degenerate facet (`stl_vertex ==` on each
// vertex pair), on a facet as `stl_read` stores it: one with a NaN
// coordinate is left all zeros, so it is degenerate too.
bool is_exact_degenerate_facet(const std::array<float, 9>& xyz) {
    for (float coordinate : xyz) {
        if (std::isnan(coordinate)) return true;
    }
    const auto same_vertex = [&xyz](int a, int b) {
        return xyz[a] == xyz[b] && xyz[a + 1] == xyz[b + 1] && xyz[a + 2] == xyz[b + 2];
    };
    return same_vertex(0, 3) || same_vertex(3, 6) || same_vertex(0, 6);
}

// The painted facets of the binary STL at `path`, for a UI `mask` (facet
// slot -> 0/1/2) that the mesh libslic3r loaded does not match 1:1.
//
// A mask comes in one of two facet orders, told apart by its length:
//   * the raw file order, which projects painted before the UI mirrored
//     libslic3r's repair still carry;
//   * the order admesh's exact pass leaves (`stl_check_facets_exact`, the
//     first step of `trianglemesh_repair_on_import`), which the UI paints
//     now (`sliceFacetOrder.ts` in the Slicer repo): each degenerate facet
//     is removed by moving the LAST facet into its slot, and the slot is
//     checked again. (Repair runs that pass a second time at the end, but
//     by then there is nothing left for it to remove, so the order stands.)
// Any other length names neither order, and pairing its slots with facets
// would be a guess, so nothing is read.
//
// The 80-byte header is the STL every caller here writes; libslic3r's one
// caller of a longer header (`.oltp`, 256 bytes) fails the size check below
// and simply gets no mapping.
//
// Streams the file instead of holding it: meshes run to millions of facets.
MaskFacetOrder load_binary_stl_painted_facets(
    const std::string& path,
    const std::vector<uint8_t>& mask,
    std::vector<RawPaintedFacet>& painted) {
    painted.clear();
    std::ifstream in(utf8_path(path), std::ios::binary);
    if (!in) return MaskFacetOrder::Unknown;
    in.seekg(0, std::ios::end);
    const auto size = in.tellg();
    if (size < 84) return MaskFacetOrder::Unknown;
    in.seekg(80, std::ios::beg);
    uint32_t count = 0;
    in.read(reinterpret_cast<char*>(&count), sizeof(count));
    if (!in) return MaskFacetOrder::Unknown;
    const auto expected_size = static_cast<std::streamoff>(84) +
        static_cast<std::streamoff>(count) * static_cast<std::streamoff>(50);
    if (size != expected_size) return MaskFacetOrder::Unknown;
    // Only ever as long as the file (the exact pass removes facets, never
    // adds); anything longer is answered before reading a single facet.
    if (mask.size() > count) return MaskFacetOrder::Unknown;

    const auto read_facet = [&in](std::array<float, 9>& xyz) {
        char rec[50];
        in.read(rec, sizeof(rec));
        std::memcpy(xyz.data(), rec + 12, sizeof(float) * xyz.size());
        return static_cast<bool>(in);
    };

    MaskFacetOrder order = MaskFacetOrder::File;
    std::vector<uint8_t> facet_value;  // file facet -> mask value
    if (mask.size() == count) {
        facet_value = mask;
    } else {
        order = MaskFacetOrder::ExactPass;
        std::vector<bool> degenerate(count);
        std::size_t kept = count;
        std::array<float, 9> xyz{};
        for (uint32_t i = 0; i < count; ++i) {
            if (!read_facet(xyz)) return MaskFacetOrder::Unknown;
            if (is_exact_degenerate_facet(xyz)) {
                degenerate[i] = true;
                --kept;
            }
        }
        if (mask.size() != kept) return MaskFacetOrder::Unknown;

        std::vector<uint32_t> slot_facet(count);
        std::iota(slot_facet.begin(), slot_facet.end(), 0u);
        for (std::size_t slot = 0, remaining = count; slot < remaining;) {
            if (degenerate[slot_facet[slot]]) {
                slot_facet[slot] = slot_facet[--remaining];
            } else {
                ++slot;
            }
        }
        facet_value.assign(count, 0);
        for (std::size_t slot = 0; slot < kept; ++slot) {
            facet_value[slot_facet[slot]] = mask[slot];
        }
        in.clear();
        in.seekg(84, std::ios::beg);
    }

    for (uint32_t i = 0; i < count; ++i) {
        RawPaintedFacet facet;
        if (!read_facet(facet.xyz)) {
            painted.clear();
            return MaskFacetOrder::Unknown;
        }
        facet.value = facet_value[i];
        if (facet.value == 0) continue;
        // A degenerate facet is in no loaded mesh — admesh removed it before
        // the mesh existed — but a file-order mask can still paint one. Its
        // centroid is an ordinary point, so carrying it would let a sliver
        // lying on a real facet claim that facet's slot below.
        if (is_exact_degenerate_facet(facet.xyz)) continue;
        painted.push_back(facet);
    }
    return order;
}


// Print::validate reports its non-fatal warning as ONE string: each check
// overwrites the previous one (only the prime tower's collision warning is
// appended to an object's), and one message may span several lines — the
// motion-limit warnings are "what is exceeded\nOrca caps it\nwhere to raise
// the limit". So it is handed over whole, as a single entry, without the
// newline some messages end in. Empty when validate had nothing to say.
rust::Vec<rust::String> validate_warnings(const std::string& text) {
    rust::Vec<rust::String> messages;
    const size_t first = text.find_first_not_of(" \t\r\n");
    if (first == std::string::npos) return messages;
    const size_t last = text.find_last_not_of(" \t\r\n");
    messages.push_back(rust::String(text.substr(first, last - first + 1)));
    return messages;
}

// The option a caller's override sets, under the name libslic3r files it:
// PrintConfigDef::handle_legacy renames legacy spellings (`enable_wipe_tower`
// → `enable_prime_tower`) and clears the key when it drops the override — a
// key it does not know, one on its obsolete list, or a value in a legacy form
// (`outer_wall_speed = 50%`). ConfigBase::set_deserialize_nothrow takes this
// same first step and then reports success for a cleared key, so an override
// libslic3r dropped looks applied. Empty = dropped.
std::string canonical_override_key(const std::string& key, const std::string& value) {
    std::string opt_key = key;
    std::string opt_value = value;
    Slic3r::PrintConfigDef::handle_legacy(opt_key, opt_value);
    return opt_key;
}

// How a refusal or warning names an override libslic3r drops: the key alone
// when libslic3r drops that key whatever its value — unknown, or on the
// obsolete list, where a few still-registered options sit (`silent_mode`) —
// and `key=value` when it was the value's form that got it dropped.
std::string describe_ignored_override(const std::string& key, const std::string& value) {
    if (canonical_override_key(key, std::string()).empty()) {
        return key + " (unknown or obsolete key)";
    }
    return key + "=" + value + " (value in a legacy form)";
}

